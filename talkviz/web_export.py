"""Export runs for the HTML players (slides/js/fmax-player.js, slides/js/sphere-player.js).

The browser draws the animation itself (SVG, sharp at any projector size, one click per new
memory), so Python only hands over the data: one entry per simulation record, no frame plan. The
pacing (simulation steps per second in each phase of a stage) is exported as defaults the player
can override.

The data goes to a ``.js`` file that registers itself in ``window.TALK_DATA[name]``: a plain
``<script>`` tag loads it, which also works when the deck is opened from disk (file://), where
fetching a ``.json`` is blocked.
"""

from __future__ import annotations

import base64
import json

import numpy as np

from .paths import media_path


def _round(a, nd):
    return np.round(np.asarray(a, dtype=float), nd).tolist()


def _int8_b64(x, vmax):
    """Activity in [-vmax, vmax] -> int8 (-127..127), base64 (values beyond vmax saturate)."""
    q = np.clip(np.round(np.asarray(x) / vmax * 127), -127, 127).astype(np.int8)
    return base64.b64encode(q.tobytes()).decode("ascii")


def export_fmax(name, R, A, Y_x, Y_v, Y_mem, *, labels, side, plasticity_off, climb_window,
                learn_window=3_500, strides=(10, 300, 50, 300), fps=24,
                ring_threshold=0.05, trail_steps=1_500, scale_pct=99.5,
                note="2D map of the teacher memory sphere (SMACOF): distances approximate",
                draft=False):
    """Write ``slides/media/interactive/<name>.data.js`` (``draft=True``: into outputs/).

    Map coordinates are centred and scaled so the 1-99 % range of the teacher path and the
    memories fit in [-1, 1] (same equal-aspect window as FmaxAnimation). Digits are int8 on one
    fixed scale for the whole run (``scale_pct`` percentile of |x_T|), like DigitInset.
    """
    steps = R["step"]
    has_v = ~np.isnan(Y_v[:, 0])

    allY = np.vstack([np.percentile(Y_x, [1, 99], axis=0), Y_mem])
    lo, hi = allY.min(0), allY.max(0)
    centre, half = (lo + hi) / 2, (hi - lo).max() / 2

    def norm(Y):
        return (Y - centre) / half

    vmax = float(np.percentile(np.abs(R["x_T"]), scale_pct))
    eps = np.linalg.norm(R["x_S"] - R["x_T"], axis=1)
    eps_scale = np.clip(eps / np.percentile(eps, 99), 0, 1)
    Yv = norm(np.where(has_v[:, None], Y_v, 0.0))
    # the map centre the memory labels point away from (FmaxAnimation uses the path mean)
    path_centre = norm(Y_x.mean(0, keepdims=True))[0]

    data = dict(
        version=1,
        n_memories=int(A["q_mem"].shape[1]),
        labels=list(labels),
        side=int(side),
        n_records=int(len(steps)),
        events=[int(e) for e in R["events"]],
        n_steps=int(steps[-1]),
        plasticity_off=int(plasticity_off),
        F_peak=float(A["F_max"].max()),
        note=note,
        map=dict(mem=_round(norm(Y_mem), 4), centre=_round(path_centre, 4)),
        pacing=dict(
            # phase boundaries in steps after a memory is added, and steps per second in
            # (climb to F_max, rest of plasticity OFF, student learning, wandering)
            bounds=[int(climb_window), int(plasticity_off), int(plasticity_off + learn_window)],
            speeds=[int(s * fps) for s in strides],
            ring_threshold=float(ring_threshold),
            trail_steps=int(trail_steps),
        ),
        rec=dict(
            step=steps.astype(int).tolist(),
            active=R["active"].astype(int).tolist(),
            plastic=R["plasticity"].astype(int).tolist(),
            tx=_round(norm(Y_x)[:, 0], 4), ty=_round(norm(Y_x)[:, 1], 4),
            vx=_round(Yv[:, 0], 4), vy=_round(Yv[:, 1], 4),
            has_v=has_v.astype(int).tolist(),
            F=_round(A["F_max"], 5),
            q=_round(A["q_mem"].ravel(), 5),          # (n_records, n_memories), row-major
            eps=_round(eps_scale, 3),
            # degrees between the teacher (projected on the memory span) and the nearest F_max state
            angle=_round(np.where(has_v, A["angle"], np.nan), 1),
        ),
        digits=dict(vmax=vmax, x_T=_int8_b64(R["x_T"], vmax), x_S=_int8_b64(R["x_S"], vmax)),
    )
    data["rec"]["angle"] = [None if a != a else a for a in data["rec"]["angle"]]   # NaN -> null

    path = media_path("interactive", f"{name}.data.js", draft=draft)
    body = json.dumps(data, separators=(",", ":"))
    path.write_text(
        "// Generated by talkviz.web_export.export_fmax; do not edit.\n"
        f"(window.TALK_DATA = window.TALK_DATA || {{}})[{json.dumps(name)}] = {body};\n",
        encoding="utf-8")
    print(f"{len(steps)} records -> {path} ({path.stat().st_size / 1e6:.1f} MB)")
    return path


def export_sphere(name, run, *, labels, display, side, axis_order=(1, 2, 0), elev=22, azim=-48,
                  stops=(430, 1_380, 3_000, 7_500), bounds=(2_600, 3_400), speeds=(130, 750),
                  trail_time=300, digit_stride=2, scale_pct=99.5, speed_sigma=50.0, draft=False):
    """Write ``slides/media/interactive/<name>.data.js`` for slides/js/sphere-player.js.

    ``run``: the arrays of notebooks/02_sphere_transfer.py (time, c_T, gap_modes, x_T, x_S,
    U_T, patterns). Coordinates are reordered by ``axis_order`` (plotted x, y, z = u indices,
    the paper's view); memories listed in ``display`` order. ``stops``: times where a click's
    playback holds (one reveal step each); every stop but the last gets a numbered marker on the
    sphere, shown once playback reaches it. ``speeds``: simulation time per second before /
    after the times in ``bounds`` (log-blended between them). Digits keep every
    ``digit_stride``-th record, on one fixed scale (``scale_pct`` percentile of |x_T|); memory
    thumbnails use the same scale, so they look like the teacher activity at that memory.
    ``speed``: speed of the teacher's projected state c_T = U_T^T x_T on the memory subspace, from
    the trajectory smoothed by a Gaussian of ``speed_sigma`` time units (removes the noise jitter,
    keeps the drives), scaled to [0, 1] by its maximum.
    ``sx, sy, sz``: the student's activity on the same subspace, c_S = U_T^T x_S, divided by the
    teacher's in-span norm |c_T|: on the unit sphere when the cortex reproduces the replayed
    pattern, inside it (radius < 1) while it does not yet.
    ``flat``: rotation for the Hammer map of the sphere (talkviz.flatmap.best_rotation).
    """
    from scipy.ndimage import gaussian_filter1d
    from .flatmap import best_rotation
    ao = list(axis_order)
    t = run["time"]
    c = run["c_T"][:, ao]
    c_S = (run["x_S"] @ run["U_T"])[:, ao] / np.linalg.norm(c, axis=1, keepdims=True)
    mem = (run["U_T"].T @ run["patterns"])[ao][:, display].T          # (P, 3)
    flat_R = best_rotation(c / np.linalg.norm(c, axis=1, keepdims=True), mem)
    vmax = float(np.percentile(np.abs(run["x_T"]), scale_pct))
    eps = np.linalg.norm(run["x_S"] - run["x_T"], axis=1)
    eps_scale = np.clip(eps / np.percentile(eps, 99), 0, 1)
    gap = run["gap_modes"]
    dt = float(t[1] - t[0])
    c_smooth = gaussian_filter1d(run["c_T"], speed_sigma / dt, axis=0, mode="nearest")
    speed = np.linalg.norm(np.gradient(c_smooth, dt, axis=0), axis=1)

    data = dict(
        version=1,
        n_records=int(len(t)),
        side=int(side),
        labels=[labels[j] for j in display],
        axes=[f"u{k + 1}" for k in ao],
        view=dict(elev=float(elev), azim=float(azim)),
        t_end=float(t[-1]),
        gap_peak=float(gap.max()),
        speed_max=float(speed.max()), speed_sigma=float(speed_sigma),
        markers=[dict(t=float(s), x=_round(m, 4)) for s, m in
                 ((s, c[np.argmin(np.abs(t - s))] / np.linalg.norm(c[np.argmin(np.abs(t - s))]))
                  for s in stops[:-1])],
        pacing=dict(stops=[float(s) for s in stops], bounds=[float(b) for b in bounds],
                    speeds=[float(s) for s in speeds], trail_time=float(trail_time)),
        mem=_round(mem, 4),
        mem_img=[_int8_b64(run["patterns"][:, j], vmax) for j in display],
        flat=dict(proj="hammer", R=_round(flat_R, 6)),
        rec=dict(
            t=_round(t, 2),
            x=_round(c[:, 0], 4), y=_round(c[:, 1], 4), z=_round(c[:, 2], 4),
            sx=_round(c_S[:, 0], 4), sy=_round(c_S[:, 1], 4), sz=_round(c_S[:, 2], 4),
            gap=_round(gap.ravel(), 4),            # (n_records, 3), largest mode first
            eps=_round(eps_scale, 3),
            speed=_round(speed / speed.max(), 4),
            # paper panel E (when recorded): selection drive |kappa| ||eps_TS||, ||dW_S/dt||_F
            **({"drive": _round(run["drive"], 5), "dW": _round(run["dW"] * 1e3, 5)} if "drive" in run else {}),
        ),
        digits=dict(vmax=vmax, stride=int(digit_stride),
                    x_T=_int8_b64(run["x_T"][::digit_stride], vmax),
                    x_S=_int8_b64(run["x_S"][::digit_stride], vmax)),
    )

    path = media_path("interactive", f"{name}.data.js", draft=draft)
    body = json.dumps(data, separators=(",", ":"))
    path.write_text(
        "// Generated by talkviz.web_export.export_sphere; do not edit.\n"
        f"(window.TALK_DATA = window.TALK_DATA || {{}})[{json.dumps(name)}] = {body};\n",
        encoding="utf-8")
    print(f"{len(t)} records -> {path} ({path.stat().st_size / 1e6:.1f} MB)")
    return path
